// Writes src/runes.css: Alboria's runes as images for the seals of the launcher's buttons, and
// the golden embroidery at the ends of each kind of button. Run it again after changing either:
//
//   node scripts/make-runes.mjs
//
// The runes are drawn like alboria-web's src/components/Rune.astro (rings, arcs, dots and short
// strokes on a 32 × 32 grid), so the website and the launcher share one set. Each comes in the
// tones of the three seals: light on the pearl buttons' blue seal, warm on the amber ones' brown
// seal, and rose on the danger ones' red seal. A button picks its rune with data-rune.

import { writeFileSync } from "node:fs";

const RUNES = {
  door: '<path d="M9 27V14a7 7 0 0 1 14 0v13Z"/><circle cx="19" cy="19" r="1.4" fill="currentColor"/><path d="M5 27h22"/>',
  key: '<circle cx="16" cy="16" r="12"/><circle cx="16" cy="13" r="3"/><path d="M14.5 16 13 22h6l-1.5-6"/>',
  bud: '<path d="M16 27V15"/><path d="M16 15c-5-1-7-5-6-10 4 0 6 3 6 6 0-3 2-6 6-6 1 5-1 9-6 10Z"/><path d="M11 24h10"/>',
  bond: '<circle cx="12" cy="16" r="7"/><circle cx="20" cy="16" r="7"/><circle cx="16" cy="16" r="1.4" fill="currentColor"/>',
  block: '<circle cx="16" cy="16" r="12"/><path d="M8 8l16 16"/>',
  shield: '<path d="M16 4l9 3.5v7c0 6-4 10-9 12-5-2-9-6-9-12v-7Z"/><circle cx="16" cy="14" r="3"/><path d="M16 17v4"/>',
  quill: '<circle cx="16" cy="16" r="12"/><path d="M11 21c1-5 4-9 10-11-1 6-5 9-10 11Z"/><path d="M11 21l4-4"/>',
  star: '<circle cx="16" cy="16" r="12"/><path d="M16 8.5l2.2 4.6 5 .6-3.7 3.4 1 5-4.5-2.5-4.5 2.5 1-5-3.7-3.4 5-.6Z"/>',
  orbit: '<circle cx="16" cy="16" r="5"/><circle cx="16" cy="16" r="12"/><circle cx="27" cy="12" r="1.8" fill="currentColor"/><circle cx="5" cy="20" r="1.8" fill="currentColor"/>',
  pod: '<path d="M16 4c6 5 6 19 0 24-6-5-6-19 0-24Z"/><path d="M8 10c3 1 5 1 8 0s5-1 8 0"/><circle cx="16" cy="16" r="1.6" fill="currentColor"/>',
  rooms: '<circle cx="16" cy="16" r="11"/><circle cx="16" cy="5" r="2" fill="currentColor"/><circle cx="25.5" cy="21.5" r="2" fill="currentColor"/><circle cx="6.5" cy="21.5" r="2" fill="currentColor"/><circle cx="16" cy="16" r="3"/>',
  hands: '<path d="M5 18c3-1 5 1 7 3l3 3 3-3c2-2 4-4 7-3"/><path d="M9 13a7 7 0 0 1 14 0"/><circle cx="16" cy="9" r="1.6" fill="currentColor"/>',
  lock: '<circle cx="16" cy="16" r="12"/><path d="M12 15v-2a4 4 0 0 1 8 0v2"/><rect x="10.5" y="15" width="11" height="8" rx="2.5"/><circle cx="16" cy="19" r="1" fill="currentColor"/>',
  more: '<circle cx="9" cy="16" r="2" fill="currentColor"/><circle cx="16" cy="16" r="2" fill="currentColor"/><circle cx="23" cy="16" r="2" fill="currentColor"/>',
  // New in the launcher: a way back (a ring and an arrowhead turning left).
  back: '<circle cx="16" cy="16" r="12"/><path d="M18 10l-6 6 6 6"/>',
};
const TONES = { light: "#d9f1ff", warm: "#fff4c2", rose: "#ffe3e6", gold: "#c98a10" };

// The embroidery at the right end of a button (the left end is its mirror): golden thread sewn
// out from the frame. The sun's rays for the amber buttons, a vine with two leaves for the pearl
// ones, a knot of thorns for the danger ones. 20 × 30, the frame's edge at x = 1, its middle at y = 15.
const EMBROIDERY = {
  sun: '<path d="M1 15h5"/><path d="M5 15l8-8M5 15l8 8M5 15h11"/><circle cx="14.5" cy="5.5" r="1.8" fill="currentColor"/><circle cx="14.5" cy="24.5" r="1.8" fill="currentColor"/><circle cx="18" cy="15" r="1.8" fill="currentColor"/><path d="M9 11c2-1 3-3 2-5M9 19c2 1 3 3 2 5" stroke-width="1"/>',
  vine: '<path d="M1 15c4 0 5-3 8-6s6-2 6 1-3 3-4 1"/><path d="M1 15c4 0 5 3 8 6s6 2 6-1-3-3-4-1"/><path d="M9 15c3 0 5-2 9-1-3 3-6 3-9 1Z" fill="currentColor" stroke="none"/>',
  thorn: '<path d="M1 15h6l3-4 3 4 3-4 2 4"/><path d="M7 15l3 4 3-4 3 4"/><path d="M10 11V7M16 11V8M10 19v4M16 19v3" stroke-width="1"/>',
};
const THREAD = { sun: "#e9b949", vine: "#c99838", thorn: "#b8862a" };

const svg = (inner, colour, viewBox, width = 2.2) =>
  `url("data:image/svg+xml,${encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none" stroke="${colour}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round" color="${colour}">${inner}</svg>`,
  ).replace(/'/g, "%27")}")`;

// Filigree for the corners of Alboria's panels: a thread that curls in from the corner, with a leaf
// and a bead; drawn for the top left corner of a 48 × 48 box and turned for the others.
const FILIGREE = '<path d="M4 30C4 14 14 4 30 4"/><path d="M10 26c0-9 7-16 16-16"/><path d="M30 4c6 0 9 4 7 7s-6 1-5-2"/><path d="M4 30c0 6 4 9 7 7s1-6-2-5"/><path d="M17 17c4-1 8 0 11 3-4 2-8 1-11-3Z" fill="currentColor" stroke="none" opacity="0.7"/><circle cx="17" cy="17" r="2" fill="currentColor" stroke="none"/>';
const CORNERS = { tl: "", tr: "translate(48 0) scale(-1 1)", bl: "translate(0 48) scale(1 -1)", br: "translate(48 48) scale(-1 -1)" };

let css = `/* Generated by scripts/make-runes.mjs: edit that, not this. */\n\n:root {\n`;
for (const [name, inner] of Object.entries(RUNES)) {
  for (const [tone, colour] of Object.entries(TONES)) css += `  --rune-${name}-${tone}: ${svg(inner, colour, "0 0 32 32")};\n`;
}
for (const [name, inner] of Object.entries(EMBROIDERY)) css += `  --embroidery-${name}: ${svg(inner, THREAD[name], "0 0 20 30", 1.6)};\n`;
for (const [corner, transform] of Object.entries(CORNERS)) {
  css += `  --filigree-${corner}: ${svg(`<g transform="${transform}">${FILIGREE}</g>`, "#c99838", "0 0 48 48", 1.3)};\n`;
}
css += `}\n\n/* Each button's rune, in the tone of its seal. */\n`;
for (const name of Object.keys(RUNES)) {
  css += `.is-alboria .btn[data-rune="${name}"] { --seal-rune: var(--rune-${name}-light); }\n`;
  css += `.is-alboria .btn-primary[data-rune="${name}"] { --seal-rune: var(--rune-${name}-warm); }\n`;
  css += `.is-alboria .btn-danger[data-rune="${name}"] { --seal-rune: var(--rune-${name}-rose); }\n`;
}
writeFileSync(new URL("../src/runes.css", import.meta.url), css);
console.log(`src/runes.css: ${Object.keys(RUNES).length} runes, ${Object.keys(EMBROIDERY).length} embroideries`);
